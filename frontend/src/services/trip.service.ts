  async exportTripPDF(
    payload: any,
    userName: string = "Traveler",
  ): Promise<{ blob: Blob; filename: string }> {
    const filename = `TripGeni_${(payload.destination || "Itinerary").replace(/\s+/g, "_")}_${payload.duration_days || ""}Days.pdf`;

    // Try backend first
    try {
      const token = localStorage.getItem("tripgenius_token");
      const response = await this.api.post(
        "/api/trips/export-pdf",
        { ...payload, user_name: userName },
        {
          responseType: "blob",
          timeout: 30000,
          headers: token ? { Authorization: `Bearer ${token}` } : {},
        },
      );
      if (response.status === 200) {
        // Respect Content-Disposition filename if present
        const disposition = response.headers["content-disposition"];
        let finalFilename = filename;
        if (disposition) {
          const match = disposition.match(/filename="?([^"]+)"?/);
          if (match?.[1]) finalFilename = match[1];
        }
        return { blob: response.data as Blob, filename: finalFilename };
      }
    } catch {
      // Fall through to client-side generation
    }

    // Client-side PDF generation fallback (generates printable HTML)
    const blob = generateClientPDFBlob(payload, userName);
    return { blob, filename };
  }

