import axios, { AxiosError, AxiosInstance } from "axios";
import { getApiBaseUrl } from "../utils/apiConfig";

// ---------------------------------------------------------------------------
// Client-side PDF generation fallback
// Produces a printable HTML blob when the backend PDF endpoint is unreachable.
// ---------------------------------------------------------------------------
function generateClientPDFBlob(trip: any, userName: string): Blob {
  const days = trip.ai_itinerary || [];
  const daysHtml = days
    .map(
      (d: any, i: number) => `
    <div style="page-break-inside: avoid; margin-bottom: 24px; border-left: 4px solid #0ea5e9; padding-left: 16px;">
      <h3 style="color: #0ea5e9; margin-bottom: 8px;">Day ${i + 1}${d.theme ? ` — ${d.theme}` : ""}</h3>
      ${d.morning ? `<p><strong>🌅 Morning:</strong> ${d.morning.activity || ""} ${d.morning.location ? `at ${d.morning.location}` : ""} ${d.morning.estimated_cost ? `(₹${d.morning.estimated_cost})` : ""}</p>` : ""}
      ${d.afternoon ? `<p><strong>☀️ Afternoon:</strong> ${d.afternoon.activity || ""} ${d.afternoon.location ? `at ${d.afternoon.location}` : ""} ${d.afternoon.estimated_cost ? `(₹${d.afternoon.estimated_cost})` : ""}</p>` : ""}
      ${d.evening ? `<p><strong>🌙 Evening:</strong> ${d.evening.activity || ""} ${d.evening.location ? `at ${d.evening.location}` : ""} ${d.evening.estimated_cost ? `(₹${d.evening.estimated_cost})` : ""}</p>` : ""}
      ${d.lunch_recommendation ? `<p><strong>🍽️ Lunch:</strong> ${d.lunch_recommendation}</p>` : ""}
      ${d.estimated_daily_cost ? `<p><strong>💰 Est. Daily Cost: ₹${d.estimated_daily_cost}</strong></p>` : ""}
    </div>
  `,
    )
    .join("");

  const html = `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8" />
  <title>TripGeni — ${trip.destination} Itinerary</title>
  <style>
    @page { margin: 20mm; }
    body { font-family: 'Segoe UI', Arial, sans-serif; color: #1e293b; font-size: 13px; line-height: 1.6; }
    h1 { color: #0ea5e9; font-size: 24px; margin-bottom: 4px; }
    h2 { color: #0f172a; font-size: 17px; margin: 20px 0 10px; border-bottom: 2px solid #e2e8f0; padding-bottom: 6px; }
    .meta { color: #64748b; font-size: 12px; margin-bottom: 20px; }
    .budget-row { display: flex; gap: 24px; background: #f1f5f9; padding: 12px 16px; border-radius: 8px; margin-bottom: 20px; }
    .budget-item { flex: 1; }
    .budget-item strong { display: block; font-size: 15px; color: #0ea5e9; }
    p { margin: 4px 0; }
    footer { margin-top: 32px; font-size: 11px; color: #94a3b8; text-align: center; border-top: 1px solid #e2e8f0; padding-top: 12px; }
  </style>
</head>
<body>
  <h1>🌍 ${trip.trip_title || `${trip.destination} Journey`}</h1>
  <p class="meta">Prepared for ${userName} • Generated by Trip Geni AI • ${new Date().toLocaleDateString("en-IN", { dateStyle: "long" })}</p>

  <div class="budget-row">
    <div class="budget-item"><strong>₹${(trip.estimated_trip_cost || trip.budget || 0).toLocaleString("en-IN")}</strong>Estimated Total</div>
    <div class="budget-item"><strong>${trip.duration_days} Days</strong>Duration</div>
    <div class="budget-item"><strong>${trip.travelers_count || 1} Traveler${(trip.travelers_count || 1) > 1 ? "s" : ""}</strong>Group Size</div>
    <div class="budget-item"><strong>${trip.travel_style || "Leisure"}</strong>Travel Style</div>
  </div>

  ${trip.destination_summary ? `<p style="margin-bottom: 16px; color: #475569;">${trip.destination_summary}</p>` : ""}

  <h2>📅 Day-by-Day Itinerary</h2>
  ${daysHtml || "<p>No itinerary details available.</p>"}

  ${trip.recommended_hotels?.length ? `<h2>🏨 Recommended Stays</h2><ul>${trip.recommended_hotels.slice(0, 5).map((h: string) => `<li>${h}</li>`).join("")}</ul>` : ""}
  ${trip.recommended_restaurants?.length ? `<h2>🍽️ Food Recommendations</h2><ul>${trip.recommended_restaurants.slice(0, 5).map((r: string) => `<li>${r}</li>`).join("")}</ul>` : ""}
  ${trip.packing_checklist?.length ? `<h2>🎒 Packing Checklist</h2><ul>${trip.packing_checklist.slice(0, 12).map((p: string) => `<li>${p}</li>`).join("")}</ul>` : ""}
  ${trip.travel_tips?.length ? `<h2>💡 Travel Tips</h2><ul>${trip.travel_tips.slice(0, 6).map((t: string) => `<li>${t}</li>`).join("")}</ul>` : ""}

  <footer>Generated by Trip Geni AI • Sustainable Travel Intelligence • tripgeni.vercel.app</footer>
</body>
</html>`;

  return new Blob([html], { type: "text/html;charset=utf-8" });
}

